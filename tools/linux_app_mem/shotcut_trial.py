#!/usr/bin/env python3
"""Shotcut 24.04 (Ubuntu package) as the same-category substitute for 剪映 (JianYing).

One cold start per operation, on the Xvfb screen (3840x2160). Before every run the Shotcut
config and data dirs are reset to a baseline saved after a clean first start (no recent files,
no autosave, no proxies, proxies off), so every run starts from the same state.
Projects are generated by make_shotcut_projects.py (MLT XML in Shotcut's own layout); the media
(3 x 1080p30 120 s at ~16 Mbit/s, 1 x 2160p30 60 s at ~50 Mbit/s, H.264 + AAC) are made with
ffmpeg and stay in materials/shotcut/media.

Operations follow the Excel list for 剪映 (A10-S01..S10):
  s01_startup      start Shotcut with an empty project
  s02_edit         1-track 1080p project: split at 5 points, ripple-delete 2 pieces, play 30 s
  s03_multitrack   3-track 1080p project (V2/V3 picture-in-picture): play 60 s
  s04_scrub        same project: drag the playhead across the ruler and jump around for ~30 s
  s05_effects      1-track project with Gaussian blur + Glow on the clip: show its filters, play 60 s
  s06_export_4k    2160p project (60 s): File > Export Video (default preset) until done
  s07_s10_background  3-track project: play 20 s, pause, hide 2 min; restore and play 30 s
  s08_proxy_bg     4-clip project: turn on proxies (F4, "create missing proxies" -> Yes), hide 2 min
  s09_export_bg    2160p project: start the export, hide the window until the export is done

Usage: APPMEM_WSS=1 python3 shotcut_trial.py OUT_DIR [--rep=r1] [run ...]
"""
import os
import re
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from trial_common import X, click, run_trials, settle  # noqa: E402

M = Path.home() / "linux_app_mem/materials/shotcut"
MEDIA = M / "media"
BASE = Path.home() / "linux_app_mem/profiles/shotcut_baseline"
CONF, DATA = Path.home() / ".config/Meltytech", Path.home() / ".local/share/Meltytech"
LAUNCH = ["/usr/bin/shotcut"]

# Layout of the maximized main window (3840x2160, default "Editing" layout)
RULER_Y = 1962                 # timeline ruler
TRACK1_Y = 2020                # first (top) track row
T0_X, PX_PER_S = 142, 30.26    # after "zoom timeline to fit" (key 0) on a 120 s project
FILTERS_TAB = (95, 1865)       # left dock tab "Filters"
NEUTRAL = (3700, 1200)         # empty part of the right dock: focus without side effects


class Abort(RuntimeError):
    pass


def tx(seconds):
    return int(T0_X + seconds * PX_PER_S)


def evict_list():
    libs = set()
    for exe in ("/usr/bin/shotcut", "/usr/bin/melt", "/usr/bin/ffmpeg"):
        for line in subprocess.run(["ldd", exe], capture_output=True, text=True).stdout.splitlines():
            m = re.search(r"=> (/\S+)", line)
            if m:
                libs.add(m.group(1))
    return sorted(libs) + ["/usr/bin/shotcut", "/usr/bin/melt", "/usr/bin/ffmpeg",
                           "/usr/lib/x86_64-linux-gnu/mlt-7", "/usr/share/mlt-7", "/usr/lib/frei0r-1",
                           "/usr/share/shotcut", "/usr/lib/x86_64-linux-gnu/qt6", "/usr/share/fonts",
                           str(CONF), str(DATA), str(MEDIA)]


def restore_profile():
    for src, dst in ((BASE / "config", CONF), (BASE / "data", DATA)):
        dst.mkdir(parents=True, exist_ok=True)
        subprocess.run(["rsync", "-a", "--delete", f"{src}/", f"{dst}/"], check=True)


def comms(r):
    out = []
    for pid in r.pids():
        try:
            out.append(Path(f"/proc/{pid}/comm").read_text().strip())
        except OSError:
            pass
    return out


def focus(r, w):
    X(["xdotool", "windowfocus", "--sync", str(w)], check=False)
    click(w, *NEUTRAL)


def prepare(r, project=None):
    r.launch(LAUNCH + ([str(project)] if project else []))
    w = r.wait_window(" - Shotcut", timeout=90)
    r.mark("settle"); settle(r, timeout=90)
    r.maximize(w); time.sleep(2)
    if "WIDTH=3840" not in X(["xdotool", "getwindowgeometry", "--shell", w]).stdout:
        raise Abort("could not maximize the main window")
    others = [n for x, n in r.windows() if x != w and n not in ("Shotcut", "Qt Selection Owner for shotcut", "")]
    if others:
        raise Abort(f"unexpected window(s) at start: {others}")
    focus(r, w)
    if project:
        r.key(w, "0"); time.sleep(1)          # zoom timeline to fit
    settle(r, timeout=30); r.shot("loaded")
    return w


def play(r, w, seconds, from_start=True):
    if from_start:
        r.key(w, "Home"); time.sleep(0.5)
    r.key(w, "space"); time.sleep(seconds); r.key(w, "space")


def start_export(r, w, out):
    r.key(w, "ctrl+e")
    d = r.wait_window("Export File", timeout=20); time.sleep(1)
    r.key(d, "ctrl+a"); r.type(d, str(out), delay_ms=15); time.sleep(0.5); r.key(d, "Return"); time.sleep(2)
    for x, n in r.windows():
        if n == "Export File":            # the path completer swallowed Return: press Save
            g = dict(l.split("=") for l in X(["xdotool", "getwindowgeometry", "--shell", x]).stdout.split())
            click(x, int(g["WIDTH"]) - 52, int(g["HEIGHT"]) - 53); time.sleep(2)
    for _ in range(30):
        if any(c.startswith("melt") for c in comms(r)):
            return
        time.sleep(0.5)
    raise Abort("export job (melt) did not start")


def wait_gone(r, name, timeout):
    t0 = time.monotonic()
    while any(c.startswith(name) for c in comms(r)):
        if time.monotonic() - t0 > timeout:
            raise Abort(f"{name} still running after {timeout} s")
        time.sleep(1)
    return round(time.monotonic() - t0, 1)


def check_export(out):
    p = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
                        "stream=width,height:format=duration", "-of", "csv=p=0", str(out)], capture_output=True, text=True)
    return p.stdout.strip().replace("\n", " ")


# ---------------------------------------------------------------- runs ---
def s01_startup(r, d):
    prepare(r)
    r.mark("steady"); time.sleep(30); r.shot("steady")


def s02_edit(r, d):
    w = prepare(r, d / "p_single.mlt")
    r.mark("edit")
    for t in (15, 35, 55, 75, 95):       # split at the playhead
        click(w, tx(t), RULER_Y); time.sleep(0.8); r.key(w, "s"); time.sleep(1)
    for t in (25, 45):                    # ripple-delete two pieces (the second one after the shift)
        click(w, tx(t), TRACK1_Y); time.sleep(0.8); r.key(w, "x"); time.sleep(1.5)
    r.shot("edited")
    play(r, w, 30)
    r.mark("idle"); time.sleep(30)


def s03_multitrack(r, d):
    w = prepare(r, d / "p_multi.mlt")
    r.mark("preview"); play(r, w, 60); r.shot("preview")
    r.mark("idle"); time.sleep(30)


def s04_scrub(r, d):
    w = prepare(r, d / "p_multi.mlt")
    r.mark("scrub")
    X(["xdotool", "mousemove", "--window", w, str(tx(0)), str(RULER_Y), "mousedown", "1"])
    for sweep in range(4):                # drag the playhead back and forth over the whole project
        ts = range(0, 121, 2) if sweep % 2 == 0 else range(120, -1, -2)
        for t in ts:
            X(["xdotool", "mousemove", "--window", w, str(tx(t)), str(RULER_Y)]); time.sleep(0.06)
    X(["xdotool", "mouseup", "1"])
    for t in (97, 12, 64, 33, 110, 5, 81, 49, 118, 26, 72, 3, 90, 57, 15, 101, 40, 68, 8, 115):
        click(w, tx(t), RULER_Y); time.sleep(0.4)   # jump around
    r.shot("scrubbed")
    r.mark("idle"); time.sleep(30)


def s05_effects(r, d):
    w = prepare(r, d / "p_effect.mlt")
    r.mark("effects")
    click(w, tx(60), TRACK1_Y); time.sleep(1); click(w, *FILTERS_TAB); time.sleep(2)   # show the clip's filters
    play(r, w, 60); r.shot("effects")
    r.mark("idle"); time.sleep(30)


def s06_export_4k(r, d):
    w = prepare(r, d / "p_4k.mlt")
    out = d / "export_4k.mp4"
    r.mark("export"); start_export(r, w, out)
    secs = wait_gone(r, "melt", 1200); r.shot("exported")
    r.mark("idle", export_seconds=secs, output=check_export(out)); time.sleep(30)


def s07_s10_background(r, d):
    w = prepare(r, d / "p_multi.mlt")
    r.mark("idle_fg"); play(r, w, 20); time.sleep(10)
    r.mark("background"); X(["xdotool", "windowunmap", "--sync", str(w)], check=False)
    time.sleep(120)
    r.mark("restore"); X(["xdotool", "windowmap", "--sync", str(w)], check=False); time.sleep(1)
    focus(r, w); play(r, w, 30, from_start=False); r.shot("restored")
    r.mark("idle"); time.sleep(30)


def s08_proxy_bg(r, d):
    w = prepare(r, d / "p_proxy.mlt")
    r.key(w, "F4")                        # Settings > Proxy > Use Proxy
    q = None
    for _ in range(20):
        q = next((x for x, n in r.windows() if n == "Shotcut" and
                  "WIDTH=476" in X(["xdotool", "getwindowgeometry", "--shell", x]).stdout), None)
        if q:
            break
        time.sleep(0.5)
    if not q:
        raise Abort("'create missing proxies' question did not appear")
    r.shot("proxy_question"); r.key(q, "Return")   # default button: Yes
    for _ in range(30):
        if "ffmpeg" in comms(r):
            break
        time.sleep(0.5)
    else:
        raise Abort("proxy job (ffmpeg) did not start")
    r.mark("background"); X(["xdotool", "windowunmap", "--sync", str(w)], check=False)
    t0 = time.monotonic(); secs = wait_gone(r, "ffmpeg", 600)
    r.mark("background", proxies_done_s=secs)       # same phase, just a note
    time.sleep(max(0, 120 - (time.monotonic() - t0)))
    r.mark("restore"); X(["xdotool", "windowmap", "--sync", str(w)], check=False); time.sleep(3); r.shot("restored")
    r.mark("idle"); time.sleep(30)


def s09_export_bg(r, d):
    w = prepare(r, d / "p_4k.mlt")
    out = d / "export_4k.mp4"
    r.mark("export_start"); start_export(r, w, out)
    r.mark("background"); X(["xdotool", "windowunmap", "--sync", str(w)], check=False)
    secs = wait_gone(r, "melt", 1200); time.sleep(5)
    r.mark("restore", export_seconds=secs, output=check_export(out))
    X(["xdotool", "windowmap", "--sync", str(w)], check=False); time.sleep(3); r.shot("restored")
    r.mark("idle"); time.sleep(30)


RUNS = [s01_startup, s02_edit, s03_multitrack, s04_scrub, s05_effects, s06_export_4k,
        s07_s10_background, s08_proxy_bg, s09_export_bg]

if __name__ == "__main__":
    os.environ["QT_QPA_PLATFORM"] = "xcb"
    run_trials("shotcut", RUNS, M, evict_list(), "[/]usr/bin/shotcut", before_each=restore_profile)
