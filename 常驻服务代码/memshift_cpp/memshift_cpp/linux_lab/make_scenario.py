#!/usr/bin/env python3
"""Generate the 20-app scenario (16 background + 4 peak apps) as JSON.

Background apps come in three kinds: browser-like (mostly cold anonymous
memory), document-like (more clean page cache) and sync-like (a working file
kept dirty by a slow rewriter). Peak apps keep a small daily footprint and
allocate peak_mib on a peak event. Between peaks the user returns to half of
the background apps (alive: touch their memory; killed: cold relaunch), which
refills memory before the next peak.
"""
import argparse
import json


def build(p):
    if p.scale != 1.0:
        for k in ("browser_anon", "browser_clean", "doc_anon", "doc_clean", "sync_anon", "sync_dirty",
                  "peak_daily", "peak_mib"):
            setattr(p, k, int(round(getattr(p, k) * p.scale)))
        p.sync_rate = round(p.sync_rate * p.scale, 2)
        p.scale = 1.0
    apps = []
    kinds = ([("browser", p.browser_anon, p.browser_clean, 0, 0)] * 8 +
             [("doc", p.doc_anon, p.doc_clean, 0, 0)] * 4 +
             [("sync", p.sync_anon, 0, p.sync_dirty, p.sync_rate)] * 4)
    order = [0, 8, 12, 1, 9, 13, 2, 10, 14, 3, 11, 15, 4, 5, 6, 7]  # interleave kinds at launch
    for slot, k in enumerate(order):
        kind, anon, clean, dirty, rate = kinds[k]
        apps.append({"name": f"bg{slot + 1:02d}", "role": "background", "kind": kind,
                     "anon_mib": anon, "clean_mib": clean, "dirty_mib": dirty, "dirty_rate_mib_s": rate,
                     "compress_ratio": p.compress_ratio, "oom_adj": 900})
    for j in range(4):
        apps.append({"name": f"pk{j + 1:02d}", "role": "peak", "kind": "peak", "anon_mib": p.peak_daily,
                     "peak_mib": p.peak_mib, "peak_rate_mib_s": p.peak_rate, "peak_page_only": p.peak_page_only,
                     "hold_s": p.hold,
                     "peak_deadline_s": 30, "oom_adj": 200})
    bg = [a["name"] for a in apps if a["role"] == "background"]
    tl = []
    for i, n in enumerate(bg):
        tl.append({"t": 2 * i, "op": "launch", "apps": [n]})
    for j in range(4):
        tl.append({"t": 2 * len(bg) + 2 * j, "op": "launch", "apps": [f"pk{j + 1:02d}"]})
    e1, gap = p.first_peak, p.event_gap
    pairs = [["pk01", "pk02"], ["pk03", "pk04"]]
    for k in range(p.events):
        t = e1 + k * gap
        if k:
            tl.append({"t": t - p.return_before, "op": "return",
                       "apps": bg if p.return_all else (bg[:8] if k % 2 else bg[8:])})
        tl.append({"t": t, "op": "peak", "apps": pairs[k % 2]})
    return {
        "name": p.name,
        "note": f"20 apps (16 background + 4 peak), {p.events} peak events; generated by make_scenario.py",
        "generator_args": vars(p),
        "scope": {"memory_max_mib": p.memory_max, "swap_max_mib": p.swap_max,
                  **({"zswap_max_mib": p.zswap_max} if p.zswap_max >= 0 else {})},
        "duration_s": e1 + (p.events - 1) * gap + p.tail,
        "policy_kill": None if p.kill_ms <= 0 else {"window_s": 1.0, "some_ms": p.kill_ms, "cooldown_s": p.kill_cooldown},
        "memshiftd": {
            "reserve_mb": 128, "ready_free_mb": 32, "startup_grace_sec": 20, "io_some_limit_pct": 50,
            "max_boost_mb": 4096, "batch_mb": 256, "max_per_minute_mb": 16384, "app_per_minute_mb": 4096,
            "alpha": 1.0, "anon_weight": 1.0, "keep_ratio": 0.2, "episode_fraction": 0.5, "cooldown_sec": 1,
        },
        "apps": apps,
        "timeline": sorted(tl, key=lambda e: e["t"]),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", default="lab20")
    ap.add_argument("--memory-max", type=int, default=5120)
    ap.add_argument("--swap-max", type=int, default=6144)
    ap.add_argument("--zswap-max", type=int, default=-1, help="scope memory.zswap.max in MiB; -1 = leave unset")
    ap.add_argument("--compress-ratio", type=float, default=1.0, help="background anon compressibility (1 = random)")
    ap.add_argument("--scale", type=float, default=1.0, help="multiply every app size by this factor")
    ap.add_argument("--browser-anon", type=int, default=260)
    ap.add_argument("--browser-clean", type=int, default=16)
    ap.add_argument("--doc-anon", type=int, default=140)
    ap.add_argument("--doc-clean", type=int, default=100)
    ap.add_argument("--sync-anon", type=int, default=100)
    ap.add_argument("--sync-dirty", type=int, default=120)
    ap.add_argument("--sync-rate", type=float, default=1.0)
    ap.add_argument("--peak-daily", type=int, default=64)
    ap.add_argument("--peak-mib", type=int, default=1200)
    ap.add_argument("--peak-rate", type=float, default=0)
    ap.add_argument("--peak-page-only", type=int, default=1, help="1 = touch one word per page (fault-speed peak)")
    ap.add_argument("--hold", type=int, default=20)
    ap.add_argument("--first-peak", type=int, default=120)
    ap.add_argument("--event-gap", type=int, default=120)
    ap.add_argument("--events", type=int, default=3)
    ap.add_argument("--return-before", type=int, default=70)
    ap.add_argument("--return-all", type=int, default=0, help="1 = every return op covers all 16 background apps")
    ap.add_argument("--tail", type=int, default=50)
    ap.add_argument("--kill-ms", type=float, default=0, help="policy kill threshold (ms stall per 1 s); 0 = off")
    ap.add_argument("--kill-cooldown", type=float, default=1.0)
    ap.add_argument("--out", required=True)
    p = ap.parse_args()
    sc = build(p)
    with open(p.out, "w") as f:
        json.dump(sc, f, indent=1)


if __name__ == "__main__":
    main()
